"""Serve txt files directly by ingress-nginx for cloud-native applications.

For every txt file, an extra Ingress is created on its host, which returns the content in its
"configuration-snippet". The Ingresses generated by the operator are left untouched, the operator
won't remove the extra Ingresses either because they don't have the "domain-group-mapping-name" label.
"""

import re

from attrs import define

from paas_wl.bk_app.cnative.specs.constants import BKAPP_NAME_ANNO_KEY
from paas_wl.core.resource import generate_bkapp_name
from paas_wl.infras.cluster.shim import EnvClusterService
from paas_wl.infras.resources.base.base import EnhancedApiClient
from paas_wl.infras.resources.base.kres import KIngress
from paas_wl.infras.resources.utils.basic import get_client_by_app
from paas_wl.workloads.networking.ingress.constants import ANNOT_CONFIGURATION_SNIPPET, ANNOT_SKIP_FILTER_CLB
from paas_wl.workloads.networking.ingress.models import Domain as CustomDomain
from paas_wl.workloads.networking.ingress.models import TxtFile
from paasng.platform.applications.models import ModuleEnvironment

LABEL_TXT_FILE = "bkapp.paas.bk.tencent.com/txt-file"
# The label which the operator puts on the Ingresses generated from DomainGroupMapping
LABEL_DOMAIN_GROUP_MAPPING = "bkapp.paas.bk.tencent.com/domain-group-mapping-name"

ANNOT_INGRESS_CLASS = "kubernetes.io/ingress.class"
ANNOT_USE_REGEX = "nginx.ingress.kubernetes.io/use-regex"
ANNOT_BACKEND_PROTOCOL = "nginx.ingress.kubernetes.io/backend-protocol"

# The location path generated by the operator for a host owned by the app from the root path.
# Because the operator uses "rewrite-target", all paths of the host are treated as regexes, and
# the txt file's location must be a regex too, otherwise it can't take precedence over this one.
OPERATOR_ROOT_LOCATION_PATH = "/()(.*)"


@define
class HostRoute:
    """How the operator's Ingress routes a host, the txt file Ingress must follow it,
    otherwise it may be handled by another ingress controller.
    """

    ingress_class: str | None
    ingress_class_name: str | None
    backend: dict


def sync_txt_file_ingresses(env: ModuleEnvironment):
    """Make the txt file Ingresses in the cluster match the txt files of the environment.

    The files whose host isn't served by the operator's Ingresses any more are skipped.
    """
    wl_app = env.wl_app
    bkapp_name = generate_bkapp_name(env)

    with get_client_by_app(wl_app) as client:
        kres = _make_kres(client)
        routes = _get_host_routes(kres, env)
        wanted: dict[str, dict] = {}
        for txt_file in TxtFile.objects.filter(environment_id=env.id):
            if route := routes.get(txt_file.host):
                body = build_txt_file_ingress(bkapp_name, txt_file, route)
                wanted[body["metadata"]["name"]] = body

        for name, body in wanted.items():
            kres.create_or_update(
                name, namespace=wl_app.namespace, body=body, update_method="replace", auto_add_version=True
            )
        for name in _list_txt_file_ingress_names(kres, env) - wanted.keys():
            kres.delete(name, namespace=wl_app.namespace)


def get_served_hosts(env: ModuleEnvironment) -> list[str]:
    """Get the hosts which the txt files can be served on, empty if the environment isn't deployed"""
    with get_client_by_app(env.wl_app) as client:
        return sorted(_get_host_routes(_make_kres(client), env))


def delete_txt_file_ingresses(env: ModuleEnvironment):
    """Delete all txt file Ingresses of the environment"""
    wl_app = env.wl_app
    with get_client_by_app(wl_app) as client:
        kres = _make_kres(client)
        for name in _list_txt_file_ingress_names(kres, env):
            kres.delete(name, namespace=wl_app.namespace)


def is_txt_files_supported(env: ModuleEnvironment) -> bool:
    """Whether the environment can have any host owned from the root path"""
    if EnvClusterService(env).get_cluster().ingress_config.app_root_domains:
        return True
    return CustomDomain.objects.filter(environment_id=env.id, path_prefix="/").exists()


def build_txt_file_ingress(bkapp_name: str, txt_file: TxtFile, route: HostRoute) -> dict:
    """Build the Ingress manifest which serves the txt file on its host"""
    annotations = {
        ANNOT_SKIP_FILTER_CLB: "true",
        ANNOT_USE_REGEX: "true",
        ANNOT_CONFIGURATION_SNIPPET: make_configuration_snippet(txt_file.content),
    }
    if route.ingress_class:
        annotations[ANNOT_INGRESS_CLASS] = route.ingress_class

    spec: dict = {
        "rules": [
            {
                "host": txt_file.host,
                "http": {
                    "paths": [
                        {
                            "path": re.escape(txt_file.path) + "$",
                            "pathType": "ImplementationSpecific",
                            "backend": route.backend,
                        }
                    ]
                },
            }
        ]
    }
    if route.ingress_class_name:
        spec["ingressClassName"] = route.ingress_class_name

    return {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "Ingress",
        "metadata": {
            "name": f"{bkapp_name}-txt-{txt_file.pk}",
            "labels": {BKAPP_NAME_ANNO_KEY: bkapp_name, LABEL_TXT_FILE: "true"},
            "annotations": annotations,
        },
        "spec": spec,
    }


def make_configuration_snippet(content: str) -> str:
    """Make the nginx snippet which returns the content as plain text.

    The content must not contain "$", nginx expands variables in the text of "return" and there's
    no way to escape it.
    """
    escaped = content.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return (
        'default_type "text/plain; charset=utf-8";\n'
        "add_header X-Content-Type-Options nosniff always;\n"
        f'return 200 "{escaped}";\n'
    )


def _make_kres(client: EnhancedApiClient) -> KIngress:
    return KIngress(client, api_version="networking.k8s.io/v1")


def _get_host_routes(kres: KIngress, env: ModuleEnvironment) -> dict[str, HostRoute]:
    """Get the routes of the hosts which the operator's Ingresses serve from the root path"""
    wl_app = env.wl_app
    # The value is the name of the DomainGroupMapping, see `gen_domain_group_mapping_name`
    labels = {LABEL_DOMAIN_GROUP_MAPPING: wl_app.scheduler_safe_name}
    routes: dict[str, HostRoute] = {}
    for item in kres.ops_batch.list(labels=labels, namespace=wl_app.namespace).items:
        ingress = item.to_dict()
        annotations = ingress["metadata"].get("annotations") or {}
        # gRPC services don't serve plain HTTP requests
        if annotations.get(ANNOT_BACKEND_PROTOCOL, "").upper() == "GRPC":
            continue

        for rule in ingress["spec"].get("rules") or []:
            for path in (rule.get("http") or {}).get("paths") or []:
                if path.get("path") == OPERATOR_ROOT_LOCATION_PATH:
                    routes[rule["host"]] = HostRoute(
                        ingress_class=annotations.get(ANNOT_INGRESS_CLASS),
                        ingress_class_name=ingress["spec"].get("ingressClassName"),
                        backend=path["backend"],
                    )
    return routes


def _list_txt_file_ingress_names(kres: KIngress, env: ModuleEnvironment) -> set[str]:
    labels = {BKAPP_NAME_ANNO_KEY: generate_bkapp_name(env), LABEL_TXT_FILE: "true"}
    items = kres.ops_batch.list(labels=labels, namespace=env.wl_app.namespace).items
    return {item.metadata.name for item in items}
