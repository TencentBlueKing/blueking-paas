import pytest

from paas_wl.bk_app.cnative.specs.addresses import gen_domain_group_mapping_name
from paas_wl.infras.resources.base.kres import KIngress
from paas_wl.workloads.networking.ingress.constants import ANNOT_CONFIGURATION_SNIPPET
from paas_wl.workloads.networking.ingress.models import TxtFile
from paas_wl.workloads.networking.ingress.txt_files.sync import (
    ANNOT_INGRESS_CLASS,
    LABEL_DOMAIN_GROUP_MAPPING,
    LABEL_TXT_FILE,
    delete_txt_file_ingresses,
    get_served_hosts,
    make_configuration_snippet,
    sync_txt_file_ingresses,
)

pytestmark = pytest.mark.django_db(databases=["default", "workloads"])

SUBDOMAINS = ["foo.example.com", "stag-dot-foo.example.com"]
CUSTOM_DOMAIN = "custom.example.com"
BACKEND = {"service": {"name": "foo--web", "port": {"name": "http"}}}


def test_make_configuration_snippet():
    snippet = make_configuration_snippet('say "hi"\\\nbye')
    assert 'return 200 "say \\"hi\\"\\\\\\nbye";' in snippet
    assert 'default_type "text/plain; charset=utf-8";' in snippet


@pytest.mark.auto_create_ns
@pytest.mark.usefixtures("skip_if_old_k8s_version")
class TestSyncTxtFileIngresses:
    @pytest.fixture()
    def kres(self, k8s_client):
        return KIngress(k8s_client, api_version="networking.k8s.io/v1")

    @pytest.fixture(autouse=True)
    def _operator_ingresses(self, kres, bk_stag_wl_app):
        """Simulate the Ingresses generated by the operator: one for all sub-domains, one for a custom
        domain with its own ingress class, and one for a custom domain with path prefix.
        """
        for name, hosts, ingress_class, path in [
            ("foo-subdomain", SUBDOMAINS, "foo-nginx", "/()(.*)"),
            ("custom-foo", [CUSTOM_DOMAIN], "custom-nginx", "/()(.*)"),
            ("custom-foo-prefixed", ["prefixed.example.com"], "custom-nginx", "/(foo)/(.*)()"),
        ]:
            body = {
                "apiVersion": "networking.k8s.io/v1",
                "kind": "Ingress",
                "metadata": {
                    "name": name,
                    "labels": {LABEL_DOMAIN_GROUP_MAPPING: gen_domain_group_mapping_name(bk_stag_wl_app)},
                    "annotations": {ANNOT_INGRESS_CLASS: ingress_class},
                },
                "spec": {
                    "rules": [
                        {
                            "host": host,
                            "http": {
                                "paths": [{"path": path, "pathType": "ImplementationSpecific", "backend": BACKEND}]
                            },
                        }
                        for host in hosts
                    ]
                },
            }
            kres.create(name, body=body, namespace=bk_stag_wl_app.namespace)

    def list_txt_routes(self, kres, wl_app) -> list[tuple[str, str, str, str]]:
        """List the (host, path, ingress class, return statement) of the txt file Ingresses"""
        items = kres.ops_batch.list(labels={LABEL_TXT_FILE: "true"}, namespace=wl_app.namespace).items
        routes = []
        for item in items:
            ingress = item.to_dict()
            annotations = ingress["metadata"]["annotations"]
            rule = ingress["spec"]["rules"][0]
            path = rule["http"]["paths"][0]
            assert path["backend"] == BACKEND
            snippet_return = annotations[ANNOT_CONFIGURATION_SNIPPET].splitlines()[-1]
            routes.append((rule["host"], path["path"], annotations[ANNOT_INGRESS_CLASS], snippet_return))
        return sorted(routes)

    def test_get_served_hosts(self, bk_stag_env):
        assert get_served_hosts(bk_stag_env) == sorted([*SUBDOMAINS, CUSTOM_DOMAIN])

    def test_sync(self, kres, bk_stag_env, bk_stag_wl_app):
        env_id = bk_stag_env.id
        subdomain_file = TxtFile.objects.create(environment_id=env_id, host=SUBDOMAINS[0], path="/a.txt", content="v1")
        TxtFile.objects.create(environment_id=env_id, host=CUSTOM_DOMAIN, path="/a.txt", content="c")
        # The host isn't served any more, e.g. the custom domain has been deleted
        TxtFile.objects.create(environment_id=env_id, host="gone.example.com", path="/a.txt", content="g")

        sync_txt_file_ingresses(bk_stag_env)
        assert self.list_txt_routes(kres, bk_stag_wl_app) == [
            (CUSTOM_DOMAIN, r"/a\.txt$", "custom-nginx", 'return 200 "c";'),
            (SUBDOMAINS[0], r"/a\.txt$", "foo-nginx", 'return 200 "v1";'),
        ]

        subdomain_file.content = "v2"
        subdomain_file.save()
        sync_txt_file_ingresses(bk_stag_env)
        assert self.list_txt_routes(kres, bk_stag_wl_app)[1][3] == 'return 200 "v2";'

        delete_txt_file_ingresses(bk_stag_env)
        assert self.list_txt_routes(kres, bk_stag_wl_app) == []
        # The Ingresses deleted by accident are recovered in the next sync
        sync_txt_file_ingresses(bk_stag_env)
        assert len(self.list_txt_routes(kres, bk_stag_wl_app)) == 2

        subdomain_file.delete()
        sync_txt_file_ingresses(bk_stag_env)
        assert [r[0] for r in self.list_txt_routes(kres, bk_stag_wl_app)] == [CUSTOM_DOMAIN]
