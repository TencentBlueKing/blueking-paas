from typing import Dict, List

import pytest

from paas_wl.bk_app.cnative.specs.addresses import gen_domain_group_mapping_name
from paas_wl.infras.resources.base.kres import KIngress
from paas_wl.workloads.networking.ingress.constants import ANNOT_CONFIGURATION_SNIPPET
from paas_wl.workloads.networking.ingress.models import TxtFile
from paas_wl.workloads.networking.ingress.txt_files.sync import (
    ANNOT_INGRESS_CLASS,
    LABEL_DOMAIN_GROUP_MAPPING,
    LABEL_TXT_FILE,
    delete_txt_file_ingresses,
    make_configuration_snippet,
    sync_txt_file_ingresses,
)

pytestmark = pytest.mark.django_db(databases=["default", "workloads"])

SERVED_HOST = "foo.example.com"
BACKEND = {"service": {"name": "foo--web", "port": {"name": "http"}}}


def test_make_configuration_snippet():
    snippet = make_configuration_snippet('say "hi"\\\nbye')
    assert 'return 200 "say \\"hi\\"\\\\\\nbye";' in snippet
    assert 'default_type "text/plain; charset=utf-8";' in snippet


@pytest.mark.auto_create_ns
class TestSyncTxtFileIngresses:
    @pytest.fixture()
    def kres(self, k8s_client):
        return KIngress(k8s_client, api_version="networking.k8s.io/v1")

    @pytest.fixture(autouse=True)
    def _operator_ingress(self, kres, bk_stag_wl_app):
        """Simulate the Ingresses generated by the operator, one for a sub-domain and one for a
        custom domain with path prefix, which shouldn't serve txt files.
        """
        for name, host, path in [
            ("foo-prefixed", "prefixed.example.com", "/(foo)/(.*)()"),
            ("foo-subdomain", SERVED_HOST, "/()(.*)"),
        ]:
            body = self._make_operator_ingress(bk_stag_wl_app, name, host, path)
            kres.create(name, body=body, namespace=bk_stag_wl_app.namespace)

    @staticmethod
    def _make_operator_ingress(wl_app, name: str, host: str, path: str) -> Dict:
        return {
            "apiVersion": "networking.k8s.io/v1",
            "kind": "Ingress",
            "metadata": {
                "name": name,
                "labels": {LABEL_DOMAIN_GROUP_MAPPING: gen_domain_group_mapping_name(wl_app)},
                "annotations": {ANNOT_INGRESS_CLASS: "foo-nginx"},
            },
            "spec": {
                "rules": [
                    {
                        "host": host,
                        "http": {"paths": [{"path": path, "pathType": "ImplementationSpecific", "backend": BACKEND}]},
                    }
                ]
            },
        }

    def list_txt_ingresses(self, kres, wl_app) -> List[Dict]:
        items = kres.ops_batch.list(labels={LABEL_TXT_FILE: "true"}, namespace=wl_app.namespace).items
        return [item.to_dict() for item in items]

    def test_sync(self, kres, bk_stag_env, bk_stag_wl_app):
        txt_file = TxtFile.objects.create(environment_id=bk_stag_env.id, path="/verify.txt", content="v1")
        assert sync_txt_file_ingresses(bk_stag_env) == [SERVED_HOST]

        [ingress] = self.list_txt_ingresses(kres, bk_stag_wl_app)
        annotations = ingress["metadata"]["annotations"]
        assert annotations[ANNOT_INGRESS_CLASS] == "foo-nginx"
        assert 'return 200 "v1";' in annotations[ANNOT_CONFIGURATION_SNIPPET]
        rule = ingress["spec"]["rules"][0]
        assert rule["host"] == SERVED_HOST
        assert rule["http"]["paths"][0]["path"] == r"/verify\.txt$"
        assert rule["http"]["paths"][0]["backend"] == BACKEND

        txt_file.content = "v2"
        txt_file.save()
        sync_txt_file_ingresses(bk_stag_env)
        [ingress] = self.list_txt_ingresses(kres, bk_stag_wl_app)
        assert 'return 200 "v2";' in ingress["metadata"]["annotations"][ANNOT_CONFIGURATION_SNIPPET]

        delete_txt_file_ingresses(bk_stag_env)
        assert self.list_txt_ingresses(kres, bk_stag_wl_app) == []
        # The Ingresses deleted by accident are recovered in the next sync
        sync_txt_file_ingresses(bk_stag_env)
        assert len(self.list_txt_ingresses(kres, bk_stag_wl_app)) == 1

        txt_file.delete()
        sync_txt_file_ingresses(bk_stag_env)
        assert self.list_txt_ingresses(kres, bk_stag_wl_app) == []
